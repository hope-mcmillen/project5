#!/usr/bin/env python3
"""Generate lib/core/testing/seed_taxonomy.dart from supabase/seed/skills.csv.

Fake mode (lib/main_fake.dart) and widget tests search this list, so skill
search offers the same skills as the seeded database. Re-run after editing
skills.csv, then `dart format lib/core/testing/seed_taxonomy.dart`.
Standard library only.

Usage: python3 scripts/make_fake_taxonomy.py
"""
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SEED = ROOT / "supabase" / "seed" / "skills.csv"
OUT = ROOT / "lib" / "core" / "testing" / "seed_taxonomy.dart"


def dart(s: str) -> str:
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$") + "'"


def main() -> None:
    with open(SEED, newline="") as f:
        rows = list(csv.DictReader(f))
    entries = []
    for r in rows:
        aliases = [a for a in r["aliases"].split("|") if a]
        entries.append(f"  ({dart(r['name'])}, {dart(r['category'])}, [{', '.join(map(dart, aliases))}]),")
    OUT.write_text(
        "// GENERATED by scripts/make_fake_taxonomy.py from supabase/seed/skills.csv.\n"
        "// Do not edit by hand.\n\n"
        "/// The seeded skill taxonomy as (name, category, aliases), for fakes and tests.\n"
        "const seedTaxonomy = <(String, String, List<String>)>[\n"
        + "\n".join(entries)
        + "\n];\n"
    )
    print(f"wrote {OUT.relative_to(ROOT)} ({len(rows)} skills)")


if __name__ == "__main__":
    main()
