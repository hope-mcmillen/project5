// Freezes realistic inputs for the Match Score regression (AI-17). From supabase/functions:
//   deno task build:match-pairs
// Runs every seed resume through parse-resume and every seed JD through parse-job
// (mock provider = recorded Gemini output, no API calls) and writes their canonical
// skills/requirements into supabase/tests/fixtures/match_pairs.json under
// "profiles" and "jobs". Hand-written "synthetic_profiles" and "pairs" (the
// human labels) are kept as they are. The test then exercises only the formula.
import { MemoryJobRepo } from "../supabase/functions/_shared/job_repo.ts";
import { parseJob } from "../supabase/functions/_shared/job_pipeline.ts";
import { MockProvider } from "../supabase/functions/_shared/llm.ts";
import { MemoryProfileStore } from "../supabase/functions/_shared/profile_store.ts";
import { parseResume } from "../supabase/functions/_shared/resume_agent.ts";
import { seedSkillIndex } from "../supabase/functions/_shared/seed_taxonomy.ts";

const SEED = new URL("../supabase/seed/", import.meta.url);
const OUT = new URL(
  "../supabase/tests/fixtures/match_pairs.json",
  import.meta.url,
);
const TODAY = new Date("2026-10-18T12:00:00Z"); // fixed so years don't drift
const index = await seedSkillIndex();
const llm = new MockProvider();

const existing = await Deno.readTextFile(OUT).then(JSON.parse).catch(
  () => ({}),
);
const profiles: Record<string, Array<{ skill: string; years: number | null }>> = {};
const jobs: Record<
  string,
  Array<{ skill: string; required: boolean; min_years: number; weight: number }>
> = {};

for (
  const { name } of [...Deno.readDirSync(new URL("resumes/", SEED))].sort((
    a,
    b,
  ) => a.name.localeCompare(b.name))
) {
  const user = crypto.randomUUID();
  const store = new MemoryProfileStore(new Set([user]));
  const res = await parseResume({
    store,
    llm,
    index,
    now: () => TODAY,
    log: () => {},
  }, { userId: user, filename: name, bytes: await Deno.readFile(new URL(`resumes/${name}`, SEED)) });
  if (res.status !== "READY") {
    throw new Error(`${name}: ${JSON.stringify(res)}`);
  }
  profiles[name.replace(/\.(pdf|docx)$/, "")] = store.versions[0].skills
    .filter((s) => s.skill_id)
    .map((s) => ({ skill: s.skill_id!, years: s.years }))
    .sort((a, b) => a.skill.localeCompare(b.skill));
}

for (
  const { name } of [...Deno.readDirSync(new URL("jobs/", SEED))].sort((a, b) => a.name.localeCompare(b.name))
) {
  const repo = new MemoryJobRepo();
  repo.recruiters.set("rec", "co");
  const id = crypto.randomUUID();
  repo.add({
    id,
    company_id: "co",
    raw_description: await Deno.readTextFile(new URL(`jobs/${name}`, SEED)),
  });
  const res = await parseJob({ repo, llm, index, log: () => {} }, {
    jobId: id,
    userId: "rec",
  });
  if (res.parse_status !== "READY") {
    throw new Error(`${name}: ${JSON.stringify(res)}`);
  }
  jobs[name.replace(/\.txt$/, "")] = res.requirements.map((r) => ({
    skill: r.skill_id,
    required: r.required,
    min_years: r.min_years,
    weight: r.weight,
  }));
}

const out = {
  note: "AI-17 Match Score regression. profiles/jobs are generated by scripts/build_match_pairs.ts " +
    "(parse pipelines on the seed files, years as of 2026-10-18); synthetic_profiles and pairs are hand-written. " +
    "Each pair's expected band is a human judgment of fit, labeled before looking at computed scores.",
  profiles,
  synthetic_profiles: existing.synthetic_profiles ?? {},
  jobs,
  pairs: existing.pairs ?? [],
};
await Deno.writeTextFile(OUT, JSON.stringify(out, null, 2) + "\n");
console.log(
  `wrote ${Object.keys(profiles).length} profiles, ${
    Object.keys(jobs).length
  } jobs; kept ${out.pairs.length} labeled pairs`,
);
