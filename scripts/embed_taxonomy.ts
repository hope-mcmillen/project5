// Generates the taxonomy seed SQL (AI-11). From supabase/functions:
//
//   deno task embed:taxonomy            # skills.sql + skills_embeddings.sql (Gemini, ~4 calls)
//   deno task embed:taxonomy --no-embed # skills.sql only (no AI)
//
// skills.sql inserts skills.csv and skill_relations.csv. skills_embeddings.sql
// sets each skill's embedding so seeding never calls the AI. Commit both, and
// re-run after editing either CSV.
import { parseArgs } from "jsr:@std/cli@1.0.20/parse-args";
import { EMBEDDING_MODEL_TAG } from "../supabase/functions/_shared/gemini.ts";
import { getProvider } from "../supabase/functions/_shared/llm.ts";
import { skillEmbedText } from "../supabase/functions/_shared/normalize.ts";
import {
  loadSeedRelations,
  loadSeedSkills,
} from "../supabase/functions/_shared/seed_taxonomy.ts";

const SEED = new URL("../supabase/seed/", import.meta.url);
const args = parseArgs(Deno.args, { boolean: ["no-embed"] });
const q = (s: string) => `'${s.replaceAll("'", "''")}'`;
const header = (what: string) =>
  `-- ${what}\n-- GENERATED by scripts/embed_taxonomy.ts from skills.csv / skill_relations.csv. Do not edit by hand.\n`;

const skills = await loadSeedSkills();
const relations = await loadSeedRelations();

// skills.sql ------------------------------------------------------------------
const skillRows = skills.map((s) =>
  `  (${q(s.name)}, ${q(s.category)}, array[${
    s.aliases.map(q).join(", ")
  }]::text[])`
);
const relationRows = relations.map((r) =>
  `  (${q(r.skill)}, ${q(r.related)}, ${r.credit})`
);
await Deno.writeTextFile(
  new URL("skills.sql", SEED),
  `${
    header(
      `Canonical skill taxonomy: ${skills.length} skills, ${relations.length} relations (AI-01)`,
    )
  }
insert into public.skills (name, category, aliases) values
${skillRows.join(",\n")}
on conflict (name) do update set category = excluded.category, aliases = excluded.aliases;

insert into public.skill_relations (skill_id, related_skill_id, credit)
select a.id, b.id, v.credit
from (values
${relationRows.join(",\n")}
) as v(skill, related, credit)
join public.skills a on a.name = v.skill
join public.skills b on b.name = v.related
on conflict (skill_id, related_skill_id) do update set credit = excluded.credit;
`,
);
console.log(
  `wrote supabase/seed/skills.sql (${skills.length} skills, ${relations.length} relations)`,
);

if (args["no-embed"]) Deno.exit(0);

// skills_embeddings.sql --------------------------------------------------------
const llm = getProvider((
  k,
) => (k === "LLM_PROVIDER" ? "gemini" : Deno.env.get(k)));
const { vectors, model, usage } = await llm.embed(
  skills.map((s) => skillEmbedText(s.name, s.aliases)),
);
if (model !== EMBEDDING_MODEL_TAG) {
  throw new Error(`Unexpected embedding model ${model}`);
}
// 7 decimals keeps cosine error below 1e-6 at about 60% of the file size of full floats.
const lit = (v: number[]) =>
  `[${v.map((x) => Number(x.toFixed(7))).join(",")}]`;
const updates = skills.map((s, i) =>
  `update public.skills set embedding = '${
    lit(vectors[i])
  }'::extensions.vector, embedding_model = ${q(model)} where name = ${
    q(s.name)
  };`
);
await Deno.writeTextFile(
  new URL("skills_embeddings.sql", SEED),
  `${
    header(
      `Taxonomy embeddings: ${model}, text = skillEmbedText(name, aliases) (AI-11)`,
    )
  }\n${updates.join("\n")}\n`,
);
console.log(
  `wrote supabase/seed/skills_embeddings.sql (${vectors.length} vectors, ~${usage.inputTokens} tokens)`,
);
